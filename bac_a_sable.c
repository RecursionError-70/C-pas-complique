void jeu(){

    char coup[16];

    while(1){

        plateau();
        printf(" ( * _ * ) ? \n");
        scanf("%15s", coup);

        char piece = coup[1];

        int x_dep = coup[2] - 'a';
        int y_dep = '8' - coup[3];

        int x_arr = coup[6] - 'a';
        int y_arr = '8' - coup[7];

        if(x_dep < 0 || x_dep > 7 || y_dep < 0 || y_dep > 7 ||
           x_arr < 0 || x_arr > 7 || y_arr < 0 || y_arr > 7){
            printf("coup invalide.\n");
            continue;
        }

        if(faceA[y_dep][x_dep] != piece){
            printf("piece non trouve.\n");
            continue;
        }

        if(piece == 'P'){
            int valide = 0;

            if(x_arr == x_dep && y_arr == y_dep - 1 && faceA[y_arr][x_arr] == '.')
                valide = 1;

            else if(x_arr == x_dep && y_dep == 6 && y_arr == 4
                    && faceA[5][x_dep] == '.' && faceA[4][x_dep] == '.')
                valide = 1;

            if(!valide){
                printf("deplacement invalide\n");
                continue;
            }

            if(y_arr == 0){
                char promotion;
                printf("promotion :\n");
                scanf(" %c", &promotion);
                piece = promotion;
            }

            faceA[y_arr][x_arr] = piece;
            faceA[y_dep][x_dep] = '.';
        }
    }
}

    
